import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, expect, it, vi } from 'vitest';
import { CodexResidualCheck } from './CodexResidualCheck';
import { useAgentStore } from '../stores/agentStore';
import { residualSlots } from '../codexResidualContract';
const inspect = vi.hoisted(() => vi.fn());
vi.mock('../bridge', async original => ({ ...await original<object>(), inspectCodexInstallResidual: inspect }));
const reference = '12345678-1234-4123-8123-123456789abc';
const result = residualSlots.map(slot => ({ slot, state: 'missing' as const }));
beforeEach(() => { inspect.mockReset(); useAgentStore.setState({ loading: false, previewing: false }); });
it('requires an explicit click, shows fixed metadata, closes and checks again', async () => {
  inspect.mockResolvedValue(result);
  render(<CodexResidualCheck sessionRef={reference} />);
  expect(inspect).not.toHaveBeenCalled();
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  expect(await screen.findByTestId('codex-residual-result')).toHaveTextContent('所有权未知；不支持清理');
  expect(inspect).toHaveBeenCalledWith(reference);
  expect(screen.getAllByTestId('codex-residual-state')).toHaveLength(4);
  fireEvent.click(screen.getByText('关闭检查结果'));
  expect(screen.queryByTestId('codex-residual-result')).not.toBeInTheDocument();
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  await screen.findByTestId('codex-residual-result'); expect(inspect).toHaveBeenCalledTimes(2);
});
it.each(['close', 'unmount', 'busy'] as const)('ignores late success after %s', async kind => {
  let resolve!: (value: typeof result) => void;
  inspect.mockImplementation(() => new Promise(r => { resolve = r; }));
  const view = render(<CodexResidualCheck sessionRef={reference} />);
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  if (kind === 'close') fireEvent.click(screen.getByText('关闭检查结果'));
  if (kind === 'unmount') view.unmount();
  if (kind === 'busy') act(() => useAgentStore.setState({ loading: true }));
  await act(async () => resolve(result));
  expect(screen.queryByTestId('codex-residual-result')).not.toBeInTheDocument();
});
it('ignores late rejection and never renders raw errors', async () => {
  let reject!: (value: unknown) => void;
  inspect.mockImplementation(() => new Promise((_, r) => { reject = r; }));
  render(<CodexResidualCheck sessionRef={reference} />);
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  fireEvent.click(screen.getByText('关闭检查结果'));
  await act(async () => reject(new Error('C:\\private\\secret')));
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  inspect.mockRejectedValue(new Error('C:\\private\\secret'));
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  await waitFor(() => expect(screen.getByRole('alert')).not.toHaveTextContent('private'));
});
it('clears prior results and ignores responses when session reference changes', async () => {
  inspect.mockResolvedValueOnce(result);
  const view = render(<CodexResidualCheck sessionRef={reference} />);
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  await screen.findByTestId('codex-residual-result');
  view.rerender(<CodexResidualCheck sessionRef="87654321-1234-4123-8123-123456789abc" />);
  expect(screen.queryByTestId('codex-residual-result')).not.toBeInTheDocument();
  expect(inspect).toHaveBeenCalledTimes(1);
});
it.each(['resolve', 'reject'] as const)('discards pending old-session %s after a reference switch', async outcome => {
  let resolve!: (value: typeof result) => void;
  let reject!: (reason: unknown) => void;
  inspect.mockImplementationOnce(() => new Promise((yes, no) => { resolve = yes; reject = no; }));
  const view = render(<CodexResidualCheck sessionRef={reference} />);
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  const next = '87654321-1234-4123-8123-123456789abc';
  view.rerender(<CodexResidualCheck sessionRef={next} />);
  await act(async () => { if (outcome === 'resolve') resolve(result); else reject(new Error('private old target')); });
  expect(screen.queryByTestId('codex-residual-result')).not.toBeInTheDocument();
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  expect(inspect).toHaveBeenCalledTimes(1);
  inspect.mockResolvedValueOnce(result);
  fireEvent.click(screen.getByText('只读检查固定残留槽位'));
  await screen.findByTestId('codex-residual-result');
  expect(inspect).toHaveBeenLastCalledWith(next);
});
